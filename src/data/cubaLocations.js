export function getMunicipalitiesByProvince(provinceNameOrId) {
  if (!provinceNameOrId || provinceNameOrId === 'all') return [];
  const found = CUBA_PROVINCES.find(
    p => p.id === provinceNameOrId || p.name.toLowerCase() === provinceNameOrId.toLowerCase()
  );
  return found ? found.municipalities : [];
}
